// Generates src/styles/tokens.css from tokens/baseplate.tokens.json.
// Usage: pnpm tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const tokens = JSON.parse(readFileSync(resolve(root, "tokens/baseplate.tokens.json"), "utf8"))
const out = resolve(root, "src/styles/tokens.css")

const MOBILE_MAX = 809 // below the 810px tablet breakpoint

const slug = (s) => s.replace(/\//g, "-")

// "blue/500" -> var(--color-blue-500); "blue/500@16" -> 16% mix; "#hex" -> #hex
function colorRef(value) {
    if (value.startsWith("#")) return value
    const [ref, alpha] = value.split("@")
    const [palette, step] = ref.split("/")
    const cssVar = palette === "base" ? `var(--color-${step})` : `var(--color-${palette}-${step})`
    return alpha ? `color-mix(in srgb, ${cssVar} ${alpha}%, transparent)` : cssVar
}

// effect strings use {elevation.x} and {semantic/name}
function effect(str) {
    return str
        .replace(/\{elevation\.([\w-]+)\}/g, (_, k) => String(tokens.elevation[k]))
        .replace(/\{([\w/-]+)\}/g, (_, k) => `var(--bp-${slug(k)})`)
}

const lines = []
const push = (s = "") => lines.push(s)

push("/* Generated by scripts/build-tokens.mjs from tokens/baseplate.tokens.json — do not edit by hand. */")
push()

// ---------- Tailwind theme: primitives, radius, fonts, type ----------
push("@theme {")
push("  /* Baseplate replaces Tailwind's default palette so only design-system colors exist */")
push("  --color-*: initial;")
for (const [palette, steps] of Object.entries(tokens.primitives)) {
    for (const [step, hex] of Object.entries(steps)) {
        push(palette === "base" ? `  --color-${step}: ${hex};` : `  --color-${palette}-${step}: ${hex};`)
    }
}
push("  --color-transparent: transparent;")
push("  --color-current: currentColor;")
push()
push("  --radius-*: initial;")
for (const [k, v] of Object.entries(tokens.radius)) push(`  --radius-${k}: ${v}px;`)
push()
push("  --shadow-*: initial;")
for (const k of Object.keys(tokens.effects)) push(`  --shadow-${k}: var(--bp-effect-${k});`)
push()
for (const [k, v] of Object.entries(tokens.font.weight)) push(`  --font-weight-${k}: ${v};`)
push("}")
push()

// semantic colors, fonts and responsive type resolve at runtime, so map them with `inline`
push("@theme inline {")
for (const name of Object.keys(tokens.semantic)) {
    if (name.startsWith("$")) continue
    const [group, ...rest] = name.split("/")
    const prefix = { bg: "", text: "fg", border: "line" }[group] ?? group
    let tail = rest.join("-")
    if (tail === "default" && group !== "border") tail = ""
    tail = tail.replace(/-default$/, "")
    const key = [prefix, tail].filter(Boolean).join("-")
    push(`  --color-${key}: var(--bp-${slug(name)});`)
}
push("  --font-heading: var(--font-bricolage), \"Bricolage Grotesque\", ui-sans-serif, system-ui, sans-serif;")
push("  --font-sans: var(--font-geist), \"Geist\", ui-sans-serif, system-ui, sans-serif;")
push("  --font-mono: var(--font-geist-mono), \"Geist Mono\", ui-monospace, monospace;")
for (const [name, t] of Object.entries(tokens.typeScale)) {
    if (name.startsWith("$")) continue
    push(`  --text-${name}: var(--bp-type-${name}-size);`)
    push(`  --text-${name}--line-height: var(--bp-type-${name}-line-height);`)
    push(`  --text-${name}--letter-spacing: ${t.tracking / 100}em;`)
    push(`  --text-${name}--font-weight: ${tokens.font.weight[t.weight]};`)
}
push("}")
push()

// ---------- Runtime variables: semantic light/dark + responsive type ----------
const semanticBlock = (mode) =>
    Object.entries(tokens.semantic)
        .filter(([k]) => !k.startsWith("$"))
        .map(([k, v]) => `  --bp-${slug(k)}: ${colorRef(v[mode])};`)

push(":root {")
push("  color-scheme: light;")
lines.push(...semanticBlock("light"))
for (const k of Object.keys(tokens.effects)) push(`  --bp-effect-${k}: ${effect(tokens.effects[k])};`)
for (const [name, t] of Object.entries(tokens.typeScale)) {
    if (name.startsWith("$")) continue
    push(`  --bp-type-${name}-size: ${t.desktop[0]}px;`)
    push(`  --bp-type-${name}-line-height: ${t.desktop[1]}px;`)
}
push("}")
push()
push(`@media (max-width: ${MOBILE_MAX}px) {`)
push("  :root {")
for (const [name, t] of Object.entries(tokens.typeScale)) {
    if (name.startsWith("$") || (t.mobile[0] === t.desktop[0] && t.mobile[1] === t.desktop[1])) continue
    push(`    --bp-type-${name}-size: ${t.mobile[0]}px;`)
    push(`    --bp-type-${name}-line-height: ${t.mobile[1]}px;`)
}
push("  }")
push("}")
push()
// dark mode: explicit data-theme="dark", or the OS setting unless light is forced
const dark = semanticBlock("dark").map((l) => "  " + l)
push('[data-theme="dark"] {')
push("  color-scheme: dark;")
lines.push(...semanticBlock("dark"))
push("}")
push("@media (prefers-color-scheme: dark) {")
push('  :root:not([data-theme="light"]) {')
push("    color-scheme: dark;")
lines.push(...dark)
push("  }")
push("}")
// force light on a subtree (e.g. the marketing site) whatever the page theme
push('[data-theme="light"] {')
push("  color-scheme: light;")
lines.push(...semanticBlock("light"))
push("}")
push()

// ---------- Type utilities matching the Figma text styles ----------
for (const [name, t] of Object.entries(tokens.typeScale)) {
    if (name.startsWith("$")) continue
    push(`@utility type-${name} {`)
    push(`  font-family: var(--font-${t.family === "heading" ? "heading" : "sans"});`)
    push(`  font-size: var(--text-${name});`)
    push(`  line-height: var(--text-${name}--line-height);`)
    push(`  letter-spacing: var(--text-${name}--letter-spacing);`)
    push(`  font-weight: var(--text-${name}--font-weight);`)
    if (t.family === "heading") push(`  font-variation-settings: "opsz" 14, "wdth" 100;`)
    push("}")
}

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, lines.join("\n") + "\n")
console.log(`Wrote ${out}`)
